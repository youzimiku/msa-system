def dw(value):
    return sum(2 if unicodedata.east_asian_width(ch) in ("F", "W") else 1 for ch in str(value or ""))


def fit_columns(ws, widths, min_row=1, max_row=None):
    max_row = max_row or ws.max_row
    for col, base in widths.items():
        best = base
        for r in range(min_row, max_row + 1):
            v = ws.cell(row=r, column=col).value
            if v is not None:
                best = max(best, min(dw(v) + 3, 60))
        ws.column_dimensions[get_column_letter(col)].width = min(best, 60)


def write_title(ws, text, ncols, row=1):
    ws.merge_cells(start_row=row, start_column=1, end_row=row, end_column=ncols)
    c = ws.cell(row=row, column=1, value=text)
    c.font = TITLE_FONT
    c.alignment = CENTER
    ws.row_dimensions[row].height = 30
    return row + 1


def write_section(ws, text, ncols, row):
    ws.merge_cells(start_row=row, start_column=1, end_row=row, end_column=ncols)
    c = ws.cell(row=row, column=1, value=text)
    c.font = SECTION_FONT
    c.fill = SECTION_FILL
    c.alignment = LEFT
    ws.row_dimensions[row].height = 22
    return row + 1


def write_headers(ws, headers, row):
    for i, h in enumerate(headers, 1):
        c = ws.cell(row=row, column=i, value=h)
        c.font = HEADER_FONT
        c.fill = HEADER_FILL
        c.alignment = CENTER
        c.border = BORDER
    ws.row_dimensions[row].height = 22
    return row + 1


def write_rows(ws, rows, row):
    for r in rows:
        for i, v in enumerate(r, 1):
            c = ws.cell(row=row, column=i, value=v)
            c.font = BODY_FONT
            c.alignment = LEFT if i != 1 else CENTER
            c.border = BORDER
        row += 1
    return row


